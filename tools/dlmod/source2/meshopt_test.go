// The vectors come from meshoptimizer's own tests (github.com/zeux/meshoptimizer, demo/tests.cpp
// and js/meshopt_decoder.test.js), as ValveResourceFormat's tests carry them.

func indicesOf(t *testing.T, data []byte, err error) []int {
	t.Helper()
	if err != nil {
		t.Fatal(err)
	}
	out := make([]int, len(data)/4)
	for i := range out {
		out[i] = int(binary.LittleEndian.Uint32(data[4*i:]))
	}
	return out
}

func TestDecodeIndexBuffer(t *testing.T) {
	plain := []int{0, 1, 2, 2, 1, 3, 4, 6, 5, 7, 8, 9}
	cases := []struct {
		name string
		want []int
		data []byte
	}{
		{"v0", plain, []byte{0xe0, 0xf0, 0x10, 0xfe, 0xff, 0xf0, 0x0c, 0xff, 0x02, 0x02, 0x02, 0x00, 0x76, 0x87, 0x56, 0x67,
			0x78, 0xa9, 0x86, 0x65, 0x89, 0x68, 0x98, 0x01, 0x69, 0x00, 0x00}},
		{"v1 restarts", []int{0, 1, 2, 2, 1, 3, 0, 1, 2, 2, 1, 5, 2, 1, 4}, []byte{0xe1, 0xf0, 0x10, 0xfe, 0x1f, 0x3d, 0x00, 0x0a,
			0x00, 0x76, 0x87, 0x56, 0x67, 0x78, 0xa9, 0x86, 0x65, 0x89, 0x68, 0x98, 0x01, 0x69, 0x00, 0x00}},
		{"v1 more", plain, []byte{0xe1, 0xf0, 0x10, 0xfe, 0xff, 0xf0, 0x0c, 0xff, 0x02, 0x02, 0x02, 0x00, 0x76, 0x87, 0x56,
			0x67, 0x78, 0xa9, 0x86, 0x65, 0x89, 0x68, 0x98, 0x01, 0x69, 0x00, 0x00}},
		{"v1 three edges", []int{0, 1, 2, 1, 0, 3, 2, 1, 4, 0, 2, 5}, []byte{0xe1, 0xf0, 0x20, 0x30, 0x40, 0x00, 0x76, 0x87,
			0x56, 0x67, 0x78, 0xa9, 0x86, 0x65, 0x89, 0x68, 0x98, 0x01, 0x69, 0x00, 0x00}},
	}
	for _, c := range cases {
		data, err := DecodeIndexBuffer(len(c.want), 4, c.data)
		if got := indicesOf(t, data, err); !reflect.DeepEqual(got, c.want) {
			t.Errorf("%s: got %v, want %v", c.name, got, c.want)
		}
	}
}

